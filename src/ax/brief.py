"""Briefs and worker definitions that carry the user's profile into delegated work.

Delegated Claude workers run with `--safe-mode`, which loads no CLAUDE.md, memory or
skills, so the brief is all they know. `ax brief KIND` builds one from a template for
the kind of work (implement, review, scout or continue): the task, the files the
worker owns, acceptance criteria, the profile rules marked for workers in that repo,
pointers to the repo's own instruction files, a permission profile, and a budget
scaled to current usage. It writes the brief outside the repo and returns the launch
plan; launching stays with the delegation skill, after the user approves the agent
count, model and effort.

`ax profile compile` also writes standing definitions for the same kinds: Claude Code
agents in `~/.claude/agents/ax-<kind>.md` and Codex profiles in
`~/.codex/ax-<kind>.config.toml` (`codex exec --profile ax-<kind>`).
"""

import json
import shlex
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from ax import usage

GENERATED = "Generated by `ax profile compile` from the vault's Profile/rules"
REPO_INSTRUCTIONS = ("AGENTS.md", "CLAUDE.md")


@dataclass(frozen=True)
class Kind:
    profile: str  # the delegation worker's permission profile
    model: str
    effort: str
    budget: float  # US dollars, before scaling to usage
    sandbox: str  # the Codex profile's sandbox
    tools: str  # the Claude agent's tools
    summary: str
    role: str


_REPORT = (
    "Report what you actually verified, with file and line evidence; do not claim a "
    "check passed unless you ran it. If you need a permission or context you lack, say "
    "so instead of working around it. Do not commit, push, publish or delegate."
)

