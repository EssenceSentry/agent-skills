# Standing definitions: `continue` needs a session, so it exists only as a brief.
DEFINED = ("implement", "review", "scout")
_SHELL = {
    "inspect": "read-only shell commands (git status, diff, log and show, ls, rg, grep, head, "
    "tail, cat, wc)",
    "verify": "read-only shell commands plus the repo's test runners (uv run pytest, ruff "
    "and pyright, .venv/bin/python -m pytest)",
}


@dataclass
class Brief:
    text: str
    plan: dict


def worker_rules(rules, repo: str | None) -> list:
    """Active rules marked for workers: the global ones and, given a repo, its own."""
    return [
        r
        for r in rules
        if r.status == "active" and "workers" in r.tools and (r.scope == "global" or r.repo == repo)
    ]


def _bullets(rules) -> list[str]:
    return [f"- {r.rule}" for r in rules]


def _windows(config) -> list:
    return usage.claude_windows(config, refresh=False)


def _budget(kind: Kind, windows) -> tuple[float, str]:
    """The kind's budget, halved when a Claude window is short; and why."""
    claude = [w for w in windows if w.provider == "claude" and w.used is not None]
    if not claude:
        return kind.budget, "Claude usage is unknown; budget left at the default."
    tight = max(claude, key=lambda w: w.used)
    name = tight.name.replace("_", " ")
    if tight.used >= 80:
        return kind.budget / 2, (
            f"Claude {name} usage is at {tight.used:.0f}%, so the budget is halved."
        )
    return kind.budget, f"Claude {name} usage is at {tight.used:.0f}%."


def _session(config, prefix: str) -> dict:
    from ax.store import Store

    found = []
    if config.db_path.exists():
        with Store(config.db_path) as store:
            found = [
                dict(r)
                for r in store.db.execute(
                    "SELECT session_id, title, ended, note_path, project FROM sessions "
                    "WHERE kind = 'main' AND note_path IS NOT NULL AND session_id LIKE ? "
                    "ORDER BY ended DESC",
                    (prefix + "%",),
                )
            ]
    if not found:
        raise ValueError(f"no archived session starts with {prefix!r}; run `ax sync` first?")
    return found[0]


def build(
    config,
    kind: str,
    *,
    repo: Path,
    task: str,
    paths=(),
    accept=(),
    diff: str | None = None,
    session: str | None = None,
    provider: str = "claude",
    windows=None,
) -> Brief:
    if kind not in KINDS:
        raise ValueError(f"unknown kind {kind!r}; choose one of {', '.join(KINDS)}")
    if kind == "continue" and not session:
        raise ValueError("a continue brief needs --session")
    from ax import profile

    spec = KINDS[kind]
    repo = Path(repo).expanduser().resolve()
    rules = worker_rules(profile.load_rules(config), repo.name)
    budget, note = _budget(spec, _windows(config) if windows is None else windows)
    lines = [f"# {kind.capitalize()} brief · {repo.name}", "", spec.role, "", "## Task", "", task]
    lines += ["", "## Scope", "", f"- Repository: {repo}"]
    owned = "You own" if kind in ("implement", "continue") else "Look at"
    lines += [f"- {owned}: " + ", ".join(f"`{p}`" for p in paths)] if paths else []
    if diff:
        lines.append(f"- The change to review: `git diff {diff}`")
    if kind == "implement":
        slug = f"{repo.name}-{datetime.now():%m%d-%H%M}"
        lines.append(
            f"- Work in a worktree if the repo has other work in progress: "
            f"`git -C {shlex.quote(str(repo))} worktree add ../{slug} -b ax/{slug}`"
        )
    if session:
        found = _session(config, session)
        note_path = config.vault / found["note_path"]
        lines.append(
            f"- Session to continue: {found['title'] or found['session_id']} "
            f"(ended {found['ended']}), note at {note_path}"
        )
    if accept:
        lines += ["", "## Acceptance criteria", "", *[f"- {a}" for a in accept]]
    if rules:
        lines += ["", "## The user's rules", "", *_bullets(rules)]
    lines += ["", "## Limits", "", _LIMITS_INTRO, f"- {_IRREVERSIBLE}"]
    lines += [f"- {x['why']} (`{x['pattern']}`)" for x in _limits(config)]
    caps = _budgets(config, repo)
    if caps:
        lines += ["", "## Budgets", "", _BUDGETS_INTRO, *[f"- {line}" for line in caps]]
    present = [repo / name for name in REPO_INSTRUCTIONS if (repo / name).exists()]
    if present:
        lines += ["", "## This repository's instructions", "", "Read these first:"]
        lines += [f"- {p}" for p in present]
    lines += ["", "## Permissions and budget", ""]
    lines.append(f"- Shell: {_SHELL.get(spec.profile, 'none')}; anything else is denied.")
    lines.append(f"- Budget: about ${budget:g}. {note}")
    lines += ["", _REPORT, ""]
    text = "\n".join(lines)
    plan = {
        "kind": kind,
        "repo": str(repo),
        "agents": 1,
        "provider": provider,
        "model": spec.model,
        "effort": spec.effort,
        "profile": spec.profile if provider == "claude" else spec.sandbox,
        "budget_usd": budget,
        "usage_note": note,
        "rules": [r.id for r in rules],
    }
    return Brief(text, plan)


_LIMITS_INTRO = (
    "These are stopped before they run, whatever the reason. If the task needs one, say so "
    "in your report; the agent that started you can run it."
)
_IRREVERSIBLE = (
    "Irreversible actions: discarding uncommitted work, deleting untracked files or stashes, "
    "a force push or a remote delete, a recursive rm outside disposable folders, cloud "
    "deletes, dropping tables."
)


_BUDGETS_INTRO = (
    'These caps reach you. Record what you spend with `ax budget add NAME AMOUNT --note "..."`, '
    "or run `ax budget reserve NAME AMOUNT` before an expensive step and `ax budget settle "
    "TICKET ACTUAL` after it. If the next step would go over, don't take it: say so in your "
    "report to the agent that started you."
)


def _budgets(config, repo) -> list[str]:
    """The open budgets of the conversation writing the brief and of the repository."""
    from ax import budget, handles
    from ax.sources.common import project_name

    here = handles.current(config)
    scopes = [f"project:{project_name(str(repo))}"] + ([f"session:{here[1]}"] if here else [])
    return [budget.line(b) for b in budget.statuses(config.data, scopes=scopes)]


def _limits(config) -> list:
    from ax import handles, policy

    here = handles.current(config)
    return policy.listing(config, session=here[1] if here else None)


def _codex_model(config) -> str:
    """The model Codex is configured with, which a Codex worker run must name."""
    import tomllib

    try:
        with open(config.codex_home / "config.toml", "rb") as f:
            return str(tomllib.load(f).get("model") or "MODEL")
    except (OSError, ValueError):
        return "MODEL"


def write(config, found: Brief) -> Brief:
    """Save the brief under ax's data folder, outside any repo, and add the launch command."""
    from ax import glue

    stem = f"{Path(found.plan['repo']).name}-{found.plan['kind']}-{datetime.now():%Y%m%d-%H%M%S}"
    path = config.data / "briefs" / f"{stem}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(found.text)
    plan = {**found.plan, "brief": str(path)}
    run_dir = str(config.data / "workers" / stem)
    if plan["provider"] == "codex":
        worker = glue.repo_skills() / "delegation" / "scripts" / "codex_worker.py"
        permission = "read-only" if KINDS[plan["kind"]].sandbox == "read-only" else "auto-review"
        plan["model"] = _codex_model(config)
        plan["command"] = [
            "python3", str(worker), "run", "--cwd", plan["repo"], "--brief", str(path),
            "--run-dir", run_dir, "--model", plan["model"], "--effort", plan["effort"],
            "--permission", permission,
        ]  # fmt: skip
    else:
        worker = glue.repo_skills() / "delegation" / "scripts" / "worker.py"
        plan["command"] = [
            "python3", str(worker), "run", "--cwd", plan["repo"], "--brief", str(path),
            "--run-dir", run_dir, "--model", plan["model"],
            "--effort", plan["effort"], "--profile", plan["profile"],
            "--max-cost-usd", f"{plan['budget_usd']:g}",
        ]  # fmt: skip
    return Brief(found.text, plan)


# standing worker definitions


def _instructions(kind: str, rules) -> list[str]:
    spec = KINDS[kind]
    lines = [spec.role, "", _REPORT]
    shared = [r for r in rules if r.scope == "global"]
    if shared:
        lines += ["", "The user's rules:", *_bullets(shared)]
    for repo in sorted({r.repo for r in rules if r.repo}):
        lines += ["", f"In {repo}:", *_bullets([r for r in rules if r.repo == repo])]
    return lines


def definitions(config, rules) -> dict[Path, str]:
    """Agent and profile files for each defined kind; empty when no rule is for workers."""
    rules = [r for r in rules if r.status == "active" and "workers" in r.tools]
    if not rules:
        return {}
    files = {}
    for kind in DEFINED:
        spec, body = KINDS[kind], _instructions(kind, rules)
        files[config.claude_home / "agents" / f"ax-{kind}.md"] = "\n".join(
            [
                "---",
                f"name: ax-{kind}",
                f"description: {spec.summary}",
                f"tools: {spec.tools}",
                f"model: {spec.model}",
                "---",
                f"<!-- {GENERATED}; edit those notes, not this file. -->",
                "",
                *body,
                "",
            ]
        )
        files[config.codex_home / f"ax-{kind}.config.toml"] = "\n".join(
            [
                f"# {GENERATED}; edit those notes, not this file.",
                f"# Use: codex exec --profile ax-{kind} --cd REPO - < BRIEF",
                f'sandbox_mode = "{spec.sandbox}"',
                'approval_policy = "never"',
                # An inherited automatic reviewer can turn "never" back into "on-request".
                'approvals_reviewer = "user"',
                f'model_reasoning_effort = "{spec.effort}"',
                f"developer_instructions = {json.dumps(chr(10).join(body), ensure_ascii=False)}",
                "",
            ]
        )
    return files
