"""One set of working rules for Claude Code and Codex, kept as notes in the vault.

Each rule is a Markdown note in `Profile/rules/` with YAML frontmatter: the rule, its
scope (global or one repo), the tools it applies to, its level (advice, check or
block), its status, the evidence behind it and when to retire it. `compile` writes the
active rules into a marked block of each tool's own instruction files and never
touches text outside the block. `check` finds instructions elsewhere that contradict
a rule, and feedback memories the profile does not cover yet.
"""

import difflib
import json
import os
import re
import subprocess
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

import yaml

LEVELS = ("advice", "check", "block")
STATUSES = ("active", "proposed", "retired", "rejected")
TOOLS = ("claude", "codex")
# "workers" is opt-in: delegated workers get a rule only when it names them.
VALID_TOOLS = (*TOOLS, "workers")
START = "<!-- ax:profile:start · generated by `ax profile compile` from the vault's Profile/rules; edit those notes, not this block -->"
END = "<!-- ax:profile:end -->"
_ID = re.compile(r"[a-z0-9][a-z0-9-]{0,62}")
_SCOPE = re.compile(r"global|repo:[A-Za-z0-9._-]+")
_BLOCK = re.compile(re.escape("<!-- ax:profile:start") + r".*?" + re.escape(END) + r"\n?", re.S)


@dataclass
class Rule:
    id: str
    rule: str
    scope: str = "global"
    tools: list = field(default_factory=lambda: list(TOOLS))
    level: str = "advice"
    status: str = "active"
    added: str = ""
    evidence: list = field(default_factory=list)
    covers: list = field(default_factory=list)  # memory names this rule supersedes
    conflicts: list = field(default_factory=list)  # regexes for contradicting lines
    allow: str = ""  # a line matching this restates the rule rather than contradicting it
    settings: dict = field(default_factory=dict)  # Claude settings.json keys it requires
    guard: dict | None = None  # a check the `ax hook guard` hook enforces
    retire_when: str = ""
    # Kept current by `ax sync` (see learn_life); `reviewed` is the user's last keep.
    maturity: str = ""
    confidence: float | None = None
    support: int | None = None
    recurrences: int | None = None
    blocks: int | None = None
    overrides: int | None = None
    last_evidence: str = ""
    review: str = ""
    reviewed: str = ""
    # A decision on a proposal: when, by whom ("you", or what decided for you), and the
    # rule that took its place. Kept, so a decision can be reversed.
    decided: str = ""
    decided_by: str = ""
    superseded_by: str = ""
    # Frontmatter keys ax doesn't know, such as Obsidian's tags and aliases, kept as written.
    extra: dict = field(default_factory=dict)
    why: str = ""
    path: Path | None = None

    @property
    def repo(self) -> str | None:
        return self.scope.split(":", 1)[1] if self.scope.startswith("repo:") else None

    def to_dict(self) -> dict:
        data = {k: v for k, v in self.__dict__.items() if k not in ("path", "why")}
        data["path"] = str(self.path) if self.path else None
        return data


@dataclass
class Change:
    path: Path
    old: str
    new: str

    def diff(self) -> str:
        return "".join(
            difflib.unified_diff(
                self.old.splitlines(keepends=True), self.new.splitlines(keepends=True),
                fromfile=str(self.path), tofile=str(self.path),
            )
        )  # fmt: skip


@dataclass
class Finding:
    kind: str  # conflict, setting or uncovered
    rule: str | None
    path: Path | None
    line: int | None
    message: str


# Written by `ax sync`; replacing a rule keeps them until the next sync recomputes them.
LIFECYCLE = ("maturity", "confidence", "support", "recurrences", "blocks", "overrides",
             "last_evidence", "review")  # fmt: skip


def rules_dir(config) -> Path:
    return config.vault / "Profile" / "rules"


def validate(rule: Rule) -> Rule:
    if not _ID.fullmatch(rule.id or ""):
        raise ValueError(f"rule id {rule.id!r} must be lowercase letters, digits and dashes")
    if not (rule.rule or "").strip():
        raise ValueError("a rule needs its text")
    if not _SCOPE.fullmatch(rule.scope):
        raise ValueError(f"scope {rule.scope!r} must be 'global' or 'repo:NAME'")
    if rule.level not in LEVELS:
        raise ValueError(f"level must be one of {', '.join(LEVELS)}")
    if rule.status not in STATUSES:
        raise ValueError(f"status must be one of {', '.join(STATUSES)}")
    if not rule.tools or set(rule.tools) - set(VALID_TOOLS):
        raise ValueError(f"tools must be among {', '.join(VALID_TOOLS)}")
    for pattern in rule.conflicts + ([rule.allow] if rule.allow else []):
        re.compile(pattern)
    return rule


def _read(path: Path) -> Rule:
    text = path.read_text()
    match = re.match(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    if not match:
        raise ValueError(f"{path} has no frontmatter")
    data = yaml.safe_load(match.group(1)) or {}
    known = {f for f in Rule.__dataclass_fields__ if f not in ("path", "why", "extra")}
    rule = Rule(
        **{k: v for k, v in data.items() if k in known},
        extra={k: v for k, v in data.items() if k not in known},
        why=match.group(2).strip(),
        path=path,
    )
    rule.added = str(rule.added or "")
    rule.reviewed = str(rule.reviewed or "")
    rule.last_evidence = str(rule.last_evidence or "")
    rule.decided = str(rule.decided or "")
    return validate(rule)


def _write(rule: Rule, path: Path) -> None:
    data = rule.to_dict()
    data.pop("path")
    extra = data.pop("extra")
    data = {k: v for k, v in data.items() if v not in (None, "", [], {})}
    data |= {k: v for k, v in extra.items() if k not in data}
    text = "---\n" + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100) + "---\n"
    if rule.why:
        text += "\n" + rule.why.strip() + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(text)
    tmp.replace(path)


def load_rules(config, *, problems: list | None = None) -> list[Rule]:
    """Every rule note. A note that can't be read raises, unless `problems` is given:
    then it is left out and recorded there as (path, error), so one typo can't stop
    something that runs unattended, such as `ax sync`."""
    folder = rules_dir(config)
    if not folder.is_dir():
        return []
    rules = []
    for path in folder.glob("*.md"):
        try:
            rules.append(_read(path))
        except (ValueError, TypeError, yaml.YAMLError) as exc:
            if problems is None:
                raise
            problems.append((path, f"{type(exc).__name__}: {exc}"))
    return sorted(rules, key=lambda r: (r.scope, r.id))


def add(config, rule_id: str, *, replace: bool = False, **fields) -> Rule:
    rule = validate(
        Rule(id=rule_id, added=fields.pop("added", None) or date.today().isoformat(), **fields)
    )
    path = rules_dir(config) / f"{rule.id}.md"
    if path.exists() and not replace:
        raise ValueError(f"rule {rule.id!r} exists; pass replace=True (--replace) to change it")
    if path.exists():
        old = _read(path)
        for name in (
            "evidence",
            "covers",
            "conflicts",
            "allow",
            "settings",
            "guard",
            "retire_when",
            *LIFECYCLE,
            "reviewed",
            "extra",
            "why",
        ):
            if not getattr(rule, name):
                setattr(rule, name, getattr(old, name))
        rule.added = old.added or rule.added
    rule.path = path
    _write(rule, path)
    return rule


