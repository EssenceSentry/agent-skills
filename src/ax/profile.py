def _repo_path(config, name: str) -> Path:
    return config.profile_repos.get(name) or config.profile_repos_root / name


def _bullets(rules) -> list[str]:
    return [f"- {' '.join(r.rule.split())}" for r in rules]


def _block(lines: list[str]) -> str:
    return "\n".join([START, "## Working rules", "", *lines, END]) + "\n"


def _merge(old: str, block: str | None) -> str:
    """Put the block in place of the old one, or at the end; None removes it."""
    if _BLOCK.search(old):
        new = _BLOCK.sub(lambda _: block or "", old, count=1)
        return re.sub(r"\n{3,}$", "\n", new) if block is None else new
    if block is None:
        return old
    if not old.strip():
        return block
    return old.rstrip("\n") + "\n\n" + block


def _targets(config, rules) -> dict[Path, str | None]:
    active = [r for r in rules if r.status == "active"]
    claude_global = [r for r in active if r.scope == "global" and "claude" in r.tools]
    codex_global = [r for r in active if r.scope == "global" and "codex" in r.tools]
    repos = sorted({r.repo for r in active if r.repo})
    codex_lines = _bullets(codex_global)
    for name in repos:
        repo_rules = [r for r in active if r.repo == name and "codex" in r.tools]
        if repo_rules:
            codex_lines += ["", f"In {name}:", *_bullets(repo_rules)]
    targets: dict[Path, str | None] = {
        config.claude_home / "CLAUDE.md": _block(_bullets(claude_global))
        if claude_global
        else None,
        config.codex_home / "AGENTS.md": _block(codex_lines) if codex_lines else None,
    }
    for name in repos:
        repo_rules = [r for r in active if r.repo == name and "claude" in r.tools]
        path = _repo_path(config, name)
        if repo_rules and path.is_dir():
            targets[path / "CLAUDE.local.md"] = _block(_bullets(repo_rules))
    # A repo whose rules were all retired keeps no stale block.
    root = config.profile_repos_root
    for local in root.glob("*/CLAUDE.local.md") if root.is_dir() else []:
        if local not in targets and _BLOCK.search(local.read_text()):
            targets[local] = None
    return targets


def missing_repos(config) -> list[str]:
    names = {r.repo for r in load_rules(config) if r.repo and r.status == "active"}
    return sorted(n for n in names if not _repo_path(config, n).is_dir())


def compile_profile(config, *, apply: bool = False) -> list[Change]:
    """The file changes the active rules call for; written only with apply=True.

    Besides each tool's instruction files, rules marked for workers produce the
    worker definitions in `ax.brief`; a hand-written file of the same name is kept.
    """
    from ax import brief

    rules = load_rules(config)
    changes = []
    for path, block in _targets(config, rules).items():
        old = path.read_text() if path.exists() else ""
        new = _merge(old, block)
        if new != old:
            changes.append(Change(path, old, new))
    for path, new in brief.definitions(config, rules).items():
        old = path.read_text() if path.exists() else ""
        if new != old and (not old or brief.GENERATED in old):
            changes.append(Change(path, old, new))
    if apply:
        for change in changes:
            change.path.parent.mkdir(parents=True, exist_ok=True)
            tmp = change.path.with_name(change.path.name + ".ax-tmp")
            tmp.write_text(change.new)
            tmp.replace(change.path)
            if change.path.name == "CLAUDE.local.md":
                _exclude_from_git(change.path)
        write_guard_rules(config)
    return changes


def write_guard_rules(config) -> Path:
    """Prebuild the block-level rules as JSON for the guard hook, which runs on every command."""
    from ax import guard

    rules = [
        {
            "id": r.id,
            "tool": r.guard.get("tool", "shell"),
            "pattern": r.guard["pattern"],
            "repo": r.guard.get("repo") or r.repo,
            "message": r.guard.get("message") or r.rule,
            "where": r.guard.get("where", "anywhere"),
        }
        for r in load_rules(config)
        if r.status == "active" and r.level == "block" and r.guard and r.guard.get("pattern")
    ]
    path = guard.rules_path(config.data)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(rules, indent=2))
    tmp.replace(path)
    return path


def _exclude_from_git(local: Path) -> None:
    """Keep a personal CLAUDE.local.md out of a shared repo without editing its .gitignore."""
    repo = local.parent
    ignored = subprocess.run(
        ["git", "-C", str(repo), "check-ignore", "-q", local.name], capture_output=True
    )
    if ignored.returncode == 0 or not (repo / ".git").is_dir():
        return
    exclude = repo / ".git" / "info" / "exclude"
    exclude.parent.mkdir(parents=True, exist_ok=True)
    text = exclude.read_text() if exclude.exists() else ""
    exclude.write_text(
        text + ("" if text.endswith("\n") or not text else "\n") + "CLAUDE.local.md\n"
    )


